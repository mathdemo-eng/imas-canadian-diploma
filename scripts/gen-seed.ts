// Generates supabase/seed.sql from the built-in content in src/content/seed.
// Run with: npm run seed:sql
// The seed only inserts rows that don't exist yet, so running it again never
// overwrites edits made in the admin panel.
import { writeFileSync } from 'node:fs';
import { seedBundle } from '../src/content/seed/index';

type Value = string | number | boolean | null | undefined | string[] | Record<string, unknown>;

function lit(v: Value): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.length ? `array[${v.map((x) => lit(x)).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${v.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, unknown>[]): string {
  if (!rows.length) return `-- ${table}: no rows\n`;
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c] as Value)).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict (id) do nothing;\n`;
}

const b = seedBundle;
const sql = [
  '-- Built-in content for the IMAS Canadian Diploma website.',
  '-- Generated by scripts/gen-seed.ts. Safe to run more than once: existing rows are kept.',
  'begin;',
  `insert into public.site_settings (id, data) values (1, ${lit(b.settings as unknown as Record<string, unknown>)}) on conflict (id) do nothing;`,
  insert('courses', b.courses as unknown as Record<string, unknown>[]),
  insert('tracks', b.tracks as unknown as Record<string, unknown>[]),
  insert('placements', b.placements as unknown as Record<string, unknown>[]),
  insert('partners', b.partners as unknown as Record<string, unknown>[]),
  insert('faqs', b.faqs as unknown as Record<string, unknown>[]),
  insert('announcements', b.announcements as unknown as Record<string, unknown>[]),
  insert('documents', b.documents as unknown as Record<string, unknown>[]),
  'commit;',
  '',
].join('\n');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`supabase/seed.sql written (${b.courses.length} courses, ${b.tracks.length} tracks, ${b.placements.length} placements).`);
